import type { Metadata } from "next";
import { getPublicSettings } from "@/server/public-settings";
import { contactLinks } from "@/lib/company";
import styles from "../text.module.css";

export const metadata: Metadata = { title: "Политика конфиденциальности" };

// Шаблон политики. Перед запуском владелец должен указать юридическое лицо и проверить текст
// на соответствие законам своей страны (например, Закону РК «О персональных данных и их защите»).

export default async function PolicyPage() {
  const { company } = await getPublicSettings();
  const contacts = contactLinks(company);
  return (
    <main className={`container ${styles.text}`}>
      <h1>Политика конфиденциальности</h1>
      <p className={styles.lead}>
        Коротко: мы используем ваши данные только чтобы связаться с вами, согласовать и выполнить чистку. Не продаём и не
        передаём их рекламным сервисам.
      </p>

      <h2>Какие данные мы получаем</h2>
      <ul>
        <li>Имя, телефон и адрес — из формы заявки.</li>
        <li>Желаемые дата и время, комментарий и фотографии мебели, если вы их добавили.</li>
        <li>Состав заказа и предварительный расчёт.</li>
      </ul>

      <h2>Зачем</h2>
      <ul>
        <li>Чтобы позвонить, уточнить детали, согласовать цену и время выезда.</li>
        <li>Чтобы мастер приехал по нужному адресу и знал, что чистить.</li>
      </ul>

      <h2>Как храним</h2>
      <p>
        Данные хранятся в базе данных сайта. Фотографии доступны только по вашей приватной ссылке на заявку и владельцу
        компании в защищённом кабинете. При загрузке из фото удаляются метаданные (в том числе геопозиция).
      </p>
      <p>
        Корзина и черновик формы сохраняются только в вашем браузере, чтобы ничего не потерялось при перезагрузке
        страницы. Сайт не использует рекламные и аналитические cookie.
      </p>

      <h2>Сколько храним</h2>
      <p>Пока это нужно для выполнения заказа и учёта, либо до вашей просьбы удалить данные.</p>

      <h2>Ваши права</h2>
      <p>
        Вы можете попросить показать, исправить или удалить ваши данные.{" "}
        {contacts.length > 0 ? (
          <>
            Напишите или позвоните нам:{" "}
            {contacts.map((c, i) => (
              <span key={c.kind}>
                {i > 0 && ", "}
                <a href={c.href}>{c.label}</a>
              </span>
            ))}
            .
          </>
        ) : (
          <>Сообщите об этом мастеру при звонке.</>
        )}
      </p>

      <h2>Кто обрабатывает данные</h2>
      <p>
        {company.name}
        {company.city && `, ${company.city}`}. Реквизиты компании указываются владельцем сайта.
      </p>
    </main>
  );
}
